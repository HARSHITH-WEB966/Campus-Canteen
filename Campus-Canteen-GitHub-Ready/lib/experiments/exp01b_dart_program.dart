// Campus Canteen - Experiment 1(b): A simple Dart program.
// Prints a greeting and adds the prices of two canteen items.
//
// Run:  dart run lib/experiments/exp01b_dart_program.dart

void main() {
  print("Hello, World! Welcome to Campus Canteen.");
  int samosa = 15, tea = 10;
  int sum = samosa + tea;
  print("The sum of $samosa and $tea is $sum");
  print("Bill for 1 Samosa and 1 Tea = Rs.$sum");
}
